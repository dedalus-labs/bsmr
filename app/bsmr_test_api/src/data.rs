/// The result of running a test
#[derive(PartialEq, Eq, Debug, Clone)]
pub struct TestResult {
    // the target the test came from
    pub target: ConfiguredTargetHandle,
    // the name of the test
    pub name: String,
    // the status of running the test
    pub status: TestStatus,
    // additional optional messages
    pub msg: Option<String>,
    // the duration of the test run
    // TODO(skcd) should this be optional? why doesn't everything have duration
    pub duration: Option<Duration>,
    // the max memory used by the test
    pub max_memory_used_bytes: Option<u64>,
    // the output of the test execution (combining stdout and stderr)
    pub details: String,
    // exact identity of the execution that produced this result
    pub attempt: Option<bsmr_data::TestAttempt>,
}

/// different possible test results
#[derive(PartialEq, Eq, Debug, Clone, Dupe)]
#[allow(non_camel_case_types)]
pub enum TestStatus {
    PASS,
    FAIL,
    SKIP,
    OMITTED,
    FATAL,
    TIMEOUT,
    INFRA_FAILURE,
    // There is something called unknown, adding it here for now,
    // we can change it later on.
    UNKNOWN,
    // We also have re-runs
    RERUN,
    LISTING_SUCCESS,
    LISTING_FAILED,
}

impl TestStatus {
    pub fn parse(s: &str) -> bsmr_error::Result<TestStatus> {
        match s {
            "PASS" => Ok(TestStatus::PASS),
            "FAIL" => Ok(TestStatus::FAIL),
            "SKIP" => Ok(TestStatus::SKIP),
            "OMIT" | "OMITTED" => Ok(TestStatus::OMITTED),
            "FATAL" => Ok(TestStatus::FATAL),
            "TIMEOUT" => Ok(TestStatus::TIMEOUT),
            "INFRA_FAILURE" => Ok(TestStatus::INFRA_FAILURE),
            "SUITE_FAILURE" | "EXECUTION_FAILURE" => Ok(TestStatus::FATAL),
            "UNKNOWN" => Ok(TestStatus::UNKNOWN),
            "RERUN" => Ok(TestStatus::RERUN),
            "LISTING_SUCCESS" => Ok(TestStatus::LISTING_SUCCESS),
            "LISTING_FAILED" => Ok(TestStatus::LISTING_FAILED),
            _ => Err(bsmr_error!(ErrorTag::Input, "Unknown test status: `{}`", s)),
        }
    }
}

