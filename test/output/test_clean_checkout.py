"""Verify build, test, run, and clean leave a fresh Git checkout completely clean."""

import json
import os
import subprocess
from collections.abc import Iterator
from pathlib import Path

import pytest

CARGO_TOML = """\
[package]
name = "clean-checkout"
version = "0.1.0"
edition = "2024"
"""

CARGO_LOCK = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "clean-checkout"
version = "0.1.0"
"""

RUST_TOOLCHAIN = """\
[toolchain]
channel = "1.98.0"
"""

MAIN_RS = """\
fn answer() -> u32 {
    42
}

fn main() {
    println!("{}", answer());
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn answer_is_42() {
        assert_eq!(answer(), 42);
    }
}
"""


class CleanCheckout:
    """Manage a committed Git repository with an isolated Bessemer home."""

    def __init__(self, root: Path) -> None:
        """Create a minimal Rust repository committed to Git with no .gitignore."""
        self.binary = Path(os.environ["BSMR_BINARY"]).resolve(strict=True)
        self.root = root / "project"
        self.home = root / "home"
        self.home.mkdir()
        (self.root / "src").mkdir(parents=True)
        (self.root / "Cargo.toml").write_text(CARGO_TOML)
        (self.root / "Cargo.lock").write_text(CARGO_LOCK)
        (self.root / "rust-toolchain.toml").write_text(RUST_TOOLCHAIN)
        (self.root / "src" / "main.rs").write_text(MAIN_RS)
        self.env = os.environ | {
            "HOME": str(self.home),
            "RUSTUP_HOME": os.environ.get("RUSTUP_HOME", str(Path.home() / ".rustup")),
        }
        self.env.pop("BSMR_ISOLATION_DIR", None)
        self.git("init", "-q")
        self.git("config", "user.name", "Test User")
        self.git("config", "user.email", "test@example.com")
        self.git("add", "Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "src/main.rs")
        self.git("commit", "-q", "-m", "initial")

    def git(self, *args: str) -> subprocess.CompletedProcess[str]:
        """Run Git in the checkout and fail with diagnostics on non-zero exit."""
        result = subprocess.run(
            ["git", *args], cwd=self.root, env=self.env, capture_output=True, text=True
        )
        assert result.returncode == 0, result.stdout + result.stderr
        return result

    def bsmr(self, *args: str) -> subprocess.CompletedProcess[str]:
        """Run Bessemer with a dedicated isolation directory in the checkout."""
        result = subprocess.run(
            [str(self.binary), "--isolation-dir", "clean-checkout", *args],
            cwd=self.root,
            env=self.env,
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, result.stdout + result.stderr
        return result


@pytest.fixture
def checkout(tmp_path: Path) -> Iterator[CleanCheckout]:
    """Ensure the test daemon stops even if an assertion fails."""
    project = CleanCheckout(root=tmp_path)
    try:
        yield project
    finally:
        project.bsmr("kill")


def test_build_test_run_and_clean_leave_git_tree_untouched(checkout: CleanCheckout) -> None:
    """Build, test, run, incremental rebuild, and clean create nothing inside the checkout."""
    output_root = Path(checkout.bsmr("root", "--kind", "output").stdout.strip())
    assert output_root.is_relative_to(checkout.home.resolve() / ".bsmr" / "checkouts")

    built = json.loads(checkout.bsmr("build", "--show-full-json-output").stdout)
    executable = Path(built["root//:clean-checkout"])
    assert executable.is_relative_to(output_root)
    assert subprocess.run([executable], capture_output=True, text=True, check=True).stdout == "42\n"

    checkout.bsmr("test")
    assert checkout.bsmr("run", "root//:clean-checkout").stdout.strip() == "42"
    checkout.bsmr("build")

    assert checkout.git("status", "--ignored", "--porcelain").stdout == ""
    assert not (checkout.root / "bsmr-out").exists()
    assert not (checkout.root / ".bsmr-planner").exists()

    checkout.bsmr("clean")
    assert not executable.exists()
    assert not (output_root / "art").exists()
    assert not (output_root.parent / ".execroot" / "clean-checkout").exists()
    assert checkout.git("status", "--ignored", "--porcelain").stdout == ""
